#!/usr/bin/env python3
"""Build a real map behind a Journey course from OpenStreetMap tiles.

Writes mobile/assets/maps/<course>.webp, one picture of the whole course
area, and mobile/src/journeys/courseMaps.ts, which says where each
picture sits on the globe so JourneyMap can draw the course on top of
it. The picture is in Web Mercator, as the tiles are; JourneyMap
projects the course the same way when it has a picture.

Tiles come from tile.openstreetmap.org (© OpenStreetMap contributors,
ODbL; the app shows that line on the map). A course is a few dozen
tiles, fetched once and cached; be gentle and keep the User-Agent.

Usage:  python3 basemap.py appalachian [route-66 ...]
        python3 basemap.py --all
  --cache DIR   where tiles are kept (default: .cache/tiles here)
  --size N      longest side of the picture in pixels (default 1400)
"""
from __future__ import annotations

import argparse
import json
import math
import os
import re
import sys
import time
import urllib.request
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
MOBILE = HERE.parent.parent
GEOMETRY = MOBILE / 'src' / 'journeys' / 'courseGeometry.ts'
OUT_DIR = MOBILE / 'assets' / 'maps'
MANIFEST = MOBILE / 'src' / 'journeys' / 'courseMaps.ts'
UA = 'Hound journeys basemap build/1.0 (https://github.com/sigmasteve/hound)'
ATTRIBUTION = '© OpenStreetMap contributors'
# The same padding JourneyMap gives a course without a picture.
PAD = 0.08


def merc(lat: float, lng: float) -> tuple[float, float]:
    x = (lng + 180) / 360
    y = (1 - math.log(math.tan(math.radians(lat)) + 1 / math.cos(math.radians(lat))) / math.pi) / 2
    return x, y


def unmerc(x: float, y: float) -> tuple[float, float]:
    lng = x * 360 - 180
    lat = math.degrees(math.atan(math.sinh(math.pi * (1 - 2 * y))))
    return lat, lng


def course_paths() -> dict[str, list[list[float]]]:
    src = GEOMETRY.read_text()
    out = {}
    for m in re.finditer(r"'([a-z0-9-]+)': \{\s*path: (\[\[.*?\]\]),", src, re.S):
        out[m.group(1)] = json.loads(m.group(2))
    return out


def fetch_tile(cache: Path, z: int, x: int, y: int) -> Image.Image:
    f = cache / f'{z}_{x}_{y}.png'
    if not f.exists():
        req = urllib.request.Request(f'https://tile.openstreetmap.org/{z}/{x}/{y}.png', headers={'User-Agent': UA})
        with urllib.request.urlopen(req, timeout=30) as r:
            f.write_bytes(r.read())
        time.sleep(0.25)
    return Image.open(f).convert('RGB')


def build(course: str, path: list[list[float]], cache: Path, size: int) -> dict:
    lats = [p[0] for p in path]
    lngs = [p[1] for p in path]
    min_lat, max_lat, min_lng, max_lng = min(lats), max(lats), min(lngs), max(lngs)
    pad_lat = (max_lat - min_lat) * PAD or 0.002
    pad_lng = (max_lng - min_lng) * PAD or 0.002
    min_lat -= pad_lat
    max_lat += pad_lat
    min_lng -= pad_lng
    max_lng += pad_lng
    x0, y1 = merc(min_lat, min_lng)
    x1, y0 = merc(max_lat, max_lng)
    # The zoom whose tiles give at least `size` pixels on the longer side.
    span = max(x1 - x0, y1 - y0)
    z = min(18, max(1, math.ceil(math.log2(size / (span * 256)))))
    scale = 256 * 2 ** z
    px0, px1, py0, py1 = x0 * scale, x1 * scale, y0 * scale, y1 * scale
    # Whole pixels, so the picture's edges are known exactly.
    px0, py0 = math.floor(px0), math.floor(py0)
    px1, py1 = math.ceil(px1), math.ceil(py1)
    tx0, tx1, ty0, ty1 = px0 // 256, (px1 - 1) // 256, py0 // 256, (py1 - 1) // 256
    n = (tx1 - tx0 + 1) * (ty1 - ty0 + 1)
    print(f'{course}: zoom {z}, {n} tiles, {px1 - px0}x{py1 - py0} px')
    sheet = Image.new('RGB', ((tx1 - tx0 + 1) * 256, (ty1 - ty0 + 1) * 256), (230, 230, 230))
    for tx in range(tx0, tx1 + 1):
        for ty in range(ty0, ty1 + 1):
            sheet.paste(fetch_tile(cache, z, tx, ty), ((tx - tx0) * 256, (ty - ty0) * 256))
    crop = sheet.crop((px0 - tx0 * 256, py0 - ty0 * 256, px1 - tx0 * 256, py1 - ty0 * 256))
    w, h = crop.size
    if max(w, h) > size:
        f = size / max(w, h)
        crop = crop.resize((round(w * f), round(h * f)), Image.LANCZOS)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out = OUT_DIR / f'{course}.webp'
    crop.save(out, 'WEBP', quality=85, method=6)
    print(f'  wrote {out.relative_to(MOBILE)} ({out.stat().st_size // 1024} KB)')
    # The picture's real edges, from the whole pixels.
    south, west = unmerc(px0 / scale, py1 / scale)
    north, east = unmerc(px1 / scale, py0 / scale)
    return {'minLat': south, 'maxLat': north, 'minLng': west, 'maxLng': east, 'width': crop.width, 'height': crop.height}


def write_manifest(entries: dict[str, dict]) -> None:
    lines = [
        '// Generated by mobile/scripts/courses/basemap.py from OpenStreetMap',
        '// tiles (© OpenStreetMap contributors, ODbL). Do not edit by hand;',
        '// re-run the script. Each picture covers exactly these bounds, in',
        '// Web Mercator; JourneyMap projects the course the same way onto it.',
        '',
        'export interface CourseMap {',
        '  source: number;',
        '  bounds: { minLat: number; maxLat: number; minLng: number; maxLng: number };',
        '  width: number;',
        '  height: number;',
        '  attribution: string;',
        '}',
        '',
        'export const COURSE_MAPS: Record<string, CourseMap> = {',
    ]
    for cid, e in sorted(entries.items()):
        b = ', '.join(f'{k}: {e[k]:.6f}' for k in ('minLat', 'maxLat', 'minLng', 'maxLng'))
        lines.append(
            f"  '{cid}': {{ source: require('../../assets/maps/{cid}.webp'), bounds: {{ {b} }}, "
            f"width: {e['width']}, height: {e['height']}, attribution: '{ATTRIBUTION}' }},"
        )
    lines += ['};', '']
    MANIFEST.write_text('\n'.join(lines))
    print(f'wrote {MANIFEST.relative_to(MOBILE)} with {len(entries)} maps')


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('courses', nargs='*')
    ap.add_argument('--all', action='store_true')
    ap.add_argument('--cache', default=str(HERE / '.cache' / 'tiles'))
    ap.add_argument('--size', type=int, default=1400)
    args = ap.parse_args()
    paths = course_paths()
    wanted = list(paths) if args.all else args.courses
    if not wanted:
        ap.error('name a course, or --all')
    cache = Path(args.cache)
    cache.mkdir(parents=True, exist_ok=True)
    # Keep what's already in the manifest for courses not rebuilt now.
    entries: dict[str, dict] = {}
    if MANIFEST.exists():
        for m in re.finditer(r"'([a-z0-9-]+)': \{ source: require\('[^']+'\), bounds: \{ minLat: ([-\d.]+), maxLat: ([-\d.]+), minLng: ([-\d.]+), maxLng: ([-\d.]+) \}, width: (\d+), height: (\d+)", MANIFEST.read_text()):
            entries[m.group(1)] = {'minLat': float(m.group(2)), 'maxLat': float(m.group(3)), 'minLng': float(m.group(4)), 'maxLng': float(m.group(5)), 'width': int(m.group(6)), 'height': int(m.group(7))}
    for cid in wanted:
        if cid not in paths:
            print(f'no such course: {cid}', file=sys.stderr)
            return 1
        entries[cid] = build(cid, paths[cid], cache, args.size)
    write_manifest(entries)
    return 0


if __name__ == '__main__':
    sys.exit(main())
